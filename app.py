st.title("🌾 Farmers Assistant Chatbot")
page = st.segmented_control("View", ["💬 Chat", "🧠 NLP Insights"], default="💬 Chat", required=True,
                            label_visibility="collapsed")


def render_chat() -> None:
    st.markdown(
        "Ask questions about farming and get answers taken **only from the documents "
        "in the knowledge base**, with the source of each answer. The assistant starts "
        "with rice cultivation, pest and disease documents, and you can upload more PDFs "
        "from the sidebar."
    )
    st.caption("Answers are only as good as the uploaded documents. Always confirm pesticide "
               "or fertiliser decisions with your local agricultural officer.")

    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            if message["role"] == "user":
                st.text(message["content"])
            else:
                show_assistant_message(message)

    question = st.chat_input(
        "Ask a question about your documents..." if documents else "Upload a document to start chatting",
        max_chars=500,
        disabled=not documents,
    )
    if not question:
        return

    previous = next((m["content"] for m in reversed(st.session_state.messages)
                     if m["role"] == "user"), None)
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.text(question)

    with st.chat_message("assistant"):
        with st.spinner("Searching documents and preparing an answer..."):
            result = kb.answer(question, min_relevance=min_relevance, top_k=top_k,
                               previous_question=previous)
        message = {
            "role": "assistant",
            "answer": result.answer,
            "status": result.status,
            "sources": result.sources,
            "query_info": result.query_info,
            "model": result.model,
        }
        show_assistant_message(message)
    st.session_state.messages.append(message)


def render_insights() -> None:
    st.markdown("This page shows the **Natural Language Processing (NLP)** steps the "
                "chatbot uses behind the scenes.")

    # --- Document statistics ---
    st.subheader("📊 Document statistics")
    if not documents:
        st.info("No documents in the knowledge base.")
    rows = []
    for doc in documents:
        stats = doc.get("stats", {})
        rows.append({
            "Document": "Original rice collection" if doc["source_type"] == "original" else doc["display_name"],
            "Pages": doc["pages"] or "-",
            "Chunks": doc["chunk_count"],
            "Words": stats.get("words", "-"),
            "Unique words": stats.get("unique_words", "-"),
            "Sentences (approx.)": stats.get("sentences", "-"),
            "Avg. sentence length": stats.get("avg_sentence_length", "-"),
            "Top keywords (TF-IDF)": ", ".join(kb.document_keywords(doc["doc_id"], 8)),
        })
    if rows:
        st.dataframe(rows, hide_index=True)

    # --- Live pipeline demo ---
    st.subheader("🔬 Try the NLP pipeline")
    sample = st.text_input("Type a question to see how it is processed",
                           value="How to control BPH in rice varieties?")
    if not sample.strip():
        return

    raw_tokens = nlp.TOKEN_PATTERN.findall(sample.lower())
    no_stop = [t for t in raw_tokens if t not in nlp.STOPWORDS]
    expanded, expansions = nlp.expand_abbreviations(sample)

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("**1. Tokenisation** (split into words)")
        st.code(" | ".join(raw_tokens) or "-")
        st.markdown("**2. Stopword removal** (drop common words)")
        st.code(" | ".join(no_stop) or "-")
        st.markdown("**3. Stemming** (reduce plural forms)")
        st.code(" | ".join(nlp.stem(t) for t in no_stop) or "-")
    with col2:
        st.markdown("**4. Abbreviation expansion** (query expansion)")
        st.code(expanded + ("\n\n" + "\n".join(expansions) if expansions else "\n\n(no abbreviations found)"))
        st.markdown("**5. Final search keywords** (used by BM25)")
        st.code(" | ".join(nlp.tokenize(expanded)) or "-")

    if documents and st.button("6. Run the search and show the ranking"):
        with st.spinner("Searching..."):
            hits, _ = kb.search(sample, top_k=5)
        st.caption("Semantic = embedding similarity (meaning). Keyword = BM25 score (exact words). "
                   "Relevance = cross-encoder re-ranker. The final order combines all three "
                   "rankings (Reciprocal Rank Fusion).")
        st.dataframe([{
            "Rank": i + 1,
            "Source": kb._citation(h["chunk"]).replace("Source: ", ""),
            "Semantic": round(h["semantic"], 3),
            "Keyword (BM25)": round(h["keyword"], 2),
            "Relevance": f"{h['score']:.0%}",
            "Text": h["chunk"]["text"][:120].replace("\n", " ") + "...",
        } for i, h in enumerate(hits)], hide_index=True)


if page == "🧠 NLP Insights":
    render_insights()
else:
    render_chat()
